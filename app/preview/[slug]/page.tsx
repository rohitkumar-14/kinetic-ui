export async function generateStaticParams() {
  try {
    const slugs = getComponentSlugs();
    return slugs.map((slug) => ({ slug }));
  } catch (e) {
    return [];
  }
}

export default async function PreviewPage(props: { params: Promise<{ slug: string }> }) {
  const { slug } = await props.params;
  
  const Component = mdxComponents[slug];
  
  if (!Component) {
    return (
      <div className="flex items-center justify-center h-screen bg-zinc-950 text-white font-mono text-sm">
        Preview not configured for '{slug}' yet. Add it to app/preview/[slug]/page.tsx
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-black">
      <Component />
    </div>
  );
}
